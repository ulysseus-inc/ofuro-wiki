/**
 * #120: メールアドレスの正規化。
 *
 * **一意性と照合の保証は DB の型（citext）が担う。** ここは表示を揃えるためのもの。
 *
 * ⚠️ **アプリ側の正規化を「保証」として当てにしないこと。**
 * メールアドレスの入口はサインアップ・サインイン・Admin作成・CSV・招待・OIDC と
 * 6つ以上あり、**1つ足し忘れれば穴が残る**。実際、同種の入口の取りこぼしを
 * 短期間に3回踏んでいる（#145 `signInOrSignUp`・#146 compose・#147 サインアップの記録）。
 *
 * そのため `users.email` / `invitations.email` は **citext** にしてある。
 * 経路によらず、DB が大文字小文字を同一視する。
 */

/**
 * 保存用にメールアドレスを整える。
 *
 * 前後の空白を落とし、小文字に揃える。
 * citext があるため照合には影響しないが、**保存値がばらつくと画面での見え方が揃わない**
 * （招待一覧・監査ログ・メンバー一覧で表記が混在する）。
 */
export function normalizeEmail(email: string): string {
  return email.trim().toLowerCase();
}
